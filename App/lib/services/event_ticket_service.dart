import 'dart:convert';

import '../../models/event_ticket_model.dart';
import 'auth_service.dart';
import 'base_service.dart';

class EventTicketService extends BaseService<EventTicketModel> {
  EventTicketService(AuthService authService)
      : super("event-tickets", authService);

  @override
  EventTicketModel fromJson(Map<String, dynamic> json) {
    return EventTicketModel.fromJson(json);
  }

  @override
  Map<String, dynamic> toJson(EventTicketModel model) {
    throw UnsupportedError('Event tickets are generated by reservations');
  }

  Future<List<EventTicketModel>> getMine() async {
    final response = await request(
      () async => client.get(
        Uri.parse('$baseUrl/$endpoint/me'),
        headers: await headers(),
      ),
    );

    return _parseList(response.body, response.statusCode);
  }

  Future<List<EventTicketModel>> getByReservation(int reservationId) async {
    final response = await request(
      () async => client.get(
        Uri.parse('$baseUrl/$endpoint/reservation/$reservationId'),
        headers: await headers(),
      ),
    );

    return _parseList(response.body, response.statusCode);
  }

  Future<List<EventTicketModel>> getByEvent(int eventId) async {
    final response = await request(
      () async => client.get(
        Uri.parse('$baseUrl/$endpoint/event/$eventId'),
        headers: await headers(),
      ),
    );

    return _parseList(response.body, response.statusCode);
  }

  Future<EventTicketQrModel> issueQr(String ticketDayId) async {
    final response = await request(
      () async => client.post(
        Uri.parse('$baseUrl/$endpoint/days/$ticketDayId/qr'),
        headers: await headers(),
      ),
    );

    return EventTicketQrModel.fromJson(jsonDecode(response.body));
  }

  Future<EventTicketCheckInResultModel> checkIn({
    required String token,
    required int eventId,
  }) async {
    final response = await request(
      () async => client.post(
        Uri.parse('$baseUrl/$endpoint/check-in'),
        headers: await headers(),
        body: jsonEncode({
          'token': token,
          'event_id': eventId,
        }),
      ),
    );

    return EventTicketCheckInResultModel.fromJson(jsonDecode(response.body));
  }

  List<EventTicketModel> _parseList(String body, int statusCode) {
    final data = jsonDecode(body);

    if (data is! List) {
      throw ApiException(statusCode, 'Formato inválido');
    }

    return data
        .map<EventTicketModel>(
          (e) => fromJson(Map<String, dynamic>.from(e)),
        )
        .toList();
  }
}
